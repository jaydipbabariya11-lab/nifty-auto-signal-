import os, streamlit as st
from dotenv import load_dotenv
from signal_engine import evaluate_signal, position_size, square_of_9_reference
load_dotenv()
st.set_page_config(page_title="NIFTY Auto Signal", page_icon="📈", layout="wide")
st.title("📈 NIFTY Auto Signal Calculator")
st.caption("Angel One SmartAPI starter • हिंदी UI • 5m + 15m confirmation")
paper = os.getenv("PAPER_MODE", "true").lower() != "false"
st.warning("LIVE BROKER FEED CONNECTED नहीं है। Manual inputs पर बना setup live signal नहीं है।")
st.info("Mode: " + ("PAPER / सुरक्षित" if paper else "LIVE configured; production review अभी आवश्यक है"))
with st.sidebar:
    st.header("Risk Settings")
    capital=st.number_input("Capital (₹)",min_value=0.0,value=50000.0,step=5000.0)
    risk_pct=st.select_slider("प्रति ट्रेड जोखिम %",options=[0.5,1.0,1.5,2.0],value=1.0)
    daily_loss=st.number_input("आज का realized loss (₹)",min_value=0.0,value=0.0,step=100.0)
    daily_limit=st.number_input("Daily loss limit (₹)",min_value=100.0,value=1000.0,step=100.0)
l,r=st.columns(2)
with l:
    st.subheader("Market & Gann levels")
    spot=st.number_input("NIFTY spot (manual)",min_value=1.0,value=22600.0,step=10.0)
    upper=st.number_input("Breakout / Gann upper",min_value=1.0,value=22850.0,step=10.0)
    lower=st.number_input("Breakdown / Gann lower",min_value=1.0,value=22450.0,step=10.0)
    st.caption("Square of 9 approximate reference — standalone signal नहीं")
    st.json(square_of_9_reference(spot))
with r:
    st.subheader("Confirmation inputs")
    trend=st.selectbox("15-minute trend",["neutral","bull","bear"],format_func=lambda x:{"neutral":"Neutral","bull":"Bullish","bear":"Bearish"}[x])
    breakout=st.selectbox("5-minute breakout close",["none","bull","bear"],format_func=lambda x:{"none":"None","bull":"Bullish breakout","bear":"Bearish breakdown"}[x])
    retest=st.selectbox("Retest",["none","bull","bear"],format_func=lambda x:{"none":"No retest","bull":"Bullish retest holds","bear":"Bearish retest holds"}[x])
    oi=st.selectbox("OI bias (manual)",["neutral","bull","bear"],format_func=lambda x:{"neutral":"Neutral / unavailable","bull":"Bullish","bear":"Bearish"}[x])
    fresh=st.checkbox("Data timestamp/freshness verify किया है",value=False)
st.subheader("Option risk & quantity")
a,b,c=st.columns(3)
with a: premium=st.number_input("Option entry premium (₹)",min_value=.05,value=120.0,step=1.0)
with b: stop=st.number_input("Premium stop-loss (₹)",min_value=.05,value=110.0,step=1.0)
with c: lot=st.number_input("Current lot size (verify)",min_value=1,value=65,step=1)
s=position_size(capital,risk_pct,premium,stop,int(lot),daily_loss,daily_limit)
if "error" in s: st.error(s["error"])
else:
    x,y,z,w=st.columns(4)
    x.metric("Risk budget",f"₹{s['risk_budget']:,.0f}")
    y.metric("Lots",str(s["lots"]))
    z.metric("Quantity",f"{s['quantity']:,}")
    w.metric("Planned premium risk",f"₹{s['planned_premium_risk']:,.0f}")
sig=evaluate_signal(spot,upper,lower,trend,breakout,retest,oi,daily_loss,daily_limit,fresh)
if sig.side=="STOP": st.error("⛔ "+sig.side+" — "+sig.reason)
elif sig.side=="WAIT": st.info("⏳ WAIT — "+sig.reason)
else: st.success("🔔 "+sig.side+" — "+sig.reason)
st.subheader("Order confirmation")
st.write("Exact expiry/strike/trading symbol/token manually verify करें; option contract auto-resolver अभी wired नहीं है.")
symbol=st.text_input("Exact option trading symbol (manual)")
confirmed=st.checkbox("मैंने expiry, strike, premium, quantity और risk verify किया और order review की अनुमति देता हूँ")
if st.button("Order review / simulate",type="primary"):
    if sig.side not in ("BUY CALL SETUP","BUY PUT SETUP"): st.error("Valid setup नहीं — order blocked.")
    elif not fresh: st.error("Fresh data verify नहीं — order blocked.")
    elif s.get("quantity",0)<=0: st.error("Risk budget में एक lot भी fit नहीं — order blocked.")
    elif not symbol.strip(): st.error("Exact trading symbol भरें.")
    elif not confirmed: st.warning("Confirmation नहीं मिली; order नहीं भेजा.")
    else:
        st.warning("Real order sending इस starter में intentionally disabled है. यह paper review ही करेगा.")
        st.json({"signal":sig.side,"instrument":symbol,"quantity":s["quantity"],"entry_premium":premium,"stop_premium":stop,"paper_mode":True})
st.caption("शैक्षिक software; financial advice नहीं। Fees, spread, slippage, volatility, rejected/partial orders और gaps से loss बढ़ सकता है.")
